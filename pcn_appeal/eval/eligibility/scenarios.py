"""Named scenarios for the real module families (pre-registered expectations).

Each is a module plus exactly what eligibility is given: the authoritative fact
view, the verified findings (and the recorded state of the others), the evidence
state, and the facts held but not trusted (uncertain / conflicted). The expected
status is the Phase 3B contract applied to the module's own gate, written before
the production evaluator was changed.

`changed` marks a scenario whose answer differs from the pre-3B behaviour because
a missing fact used to satisfy a negative condition; the reason is the note.
"""
from __future__ import annotations

from typing import Any, Optional

S, UN, RJ, BL = "SUPPORTED", "UNRESOLVED", "REJECTED", "BLOCKED"


def sc(sid: str, module: str, expect: str, view: Optional[dict] = None, *, findings=(),
       states: Optional[dict] = None, evidence=(), complete: bool = False, unreliable=(),
       role: Optional[str] = None, changed: str = "", family: str = "") -> dict:
    return {"id": sid, "module": module, "expect": expect, "view": dict(view or {}),
            "findings": list(findings), "finding_states": dict(states or {}),
            "evidence": list(evidence), "evidence_complete": complete,
            "unreliable": list(unreliable), "role": role, "changed": changed,
            "family": family or module}


